"""Embed data/waystone_data.json into src/game/WaystoneDataEmbedded.h.

The waystone affix and stat table ships inside the DLL, so the plugin needs no
data file next to it. Run after editing data/waystone_data.json:

    python tools/embed_waystone_data.py          # regenerate the header
    python tools/embed_waystone_data.py --check  # fail if the header is stale
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "data" / "waystone_data.json"
TARGET = ROOT / "src" / "game" / "WaystoneDataEmbedded.h"
CHUNK = 8000          # MSVC limits one string literal to 16380 bytes
DELIM = "WSD"


def render() -> str:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    text = json.dumps(data, separators=(",", ":"), ensure_ascii=True)
    if ")" + DELIM + '"' in text:
        raise SystemExit("raw-string delimiter occurs in the data")
    chunks = [text[i:i + CHUNK] for i in range(0, len(text), CHUNK)]
    lines = [
        "#pragma once",
        "// GENERATED by tools/embed_waystone_data.py from data/waystone_data.json -- do not edit by hand.",
        "#include <cstddef>",
        "",
        "namespace WaystoneHelper::Embedded {",
        "",
        "inline constexpr const char* kWaystoneDataChunks[] = {",
    ]
    for c in chunks:
        lines.append(f'    R"{DELIM}({c}){DELIM}",')
    lines += [
        "};",
        f"inline constexpr std::size_t kWaystoneDataChunkCount = {len(chunks)};",
        f"inline constexpr std::size_t kWaystoneDataSize = {len(text)};",
        "",
        "}  // namespace WaystoneHelper::Embedded",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    wanted = render()
    if "--check" in sys.argv[1:]:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current.replace("\r\n", "\n") != wanted:
            print(f"{TARGET.name} is stale: run tools/embed_waystone_data.py")
            return 1
        print(f"{TARGET.name} is up to date")
        return 0
    TARGET.write_text(wanted, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.name} ({len(wanted)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
